// Generates the seed SQL from the frontend data files so they never drift apart:
//   supabase/seed/menu.sql  ← src/data/menu.js   (real owner-supplied menu; safe for production)
//   supabase/seed/demo.sql  ← src/data/sample.js (labelled sample data; development only)
// Run: npm run seed:generate
import { writeFileSync } from 'node:fs';
import { openingHours, testimonials, homeContent } from '../src/data/sample.js';
import { menuCategories, menuItems } from '../src/data/menu.js';

const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const DAYS = { Monday: 1, Tuesday: 2, Wednesday: 3, Thursday: 4, Friday: 5, Saturday: 6, Sunday: 7 };

let sql = `-- DEMO / SAMPLE DATA — NOT REAL SAVORA BUSINESS INFORMATION.
-- Generated by scripts/generate-demo-seed.mjs from src/data/sample.js. Do not edit by hand.
-- Load only into development or staging. Every content row is flagged is_sample = true.
-- To remove it later: delete from menu_items where is_sample; delete from menu_categories where is_sample; ...

begin;

-- Dining areas and tables (placeholder layout: owner to replace with the real floor plan)
insert into public.dining_areas (key, name, sort_order) values
  ('indoor', 'Indoor', 1), ('outdoor', 'Outdoor', 2), ('private', 'Private dining', 3);

insert into public.restaurant_tables (label, area_id, min_capacity, max_capacity)
select t.label, a.id, t.min_c, t.max_c
from (values
  ('T1','indoor',1,2), ('T2','indoor',1,2), ('T3','indoor',2,4), ('T4','indoor',2,4), ('T5','indoor',2,4),
  ('T6','indoor',4,6), ('T7','indoor',4,6), ('P1','outdoor',1,2), ('P2','outdoor',2,4), ('P3','outdoor',2,4),
  ('PD1','private',6,12)
) as t(label, area, min_c, max_c)
join public.dining_areas a on a.key = t.area;

-- Opening hours (sample)
insert into public.opening_hours (day_of_week, opens_at, closes_at) values
${openingHours.days.map((d) => `  (${DAYS[d.day]}, '${d.open}', '${d.close}')`).join(',\n')};

-- Website copy
insert into public.content_sections (page, section, title, body, is_sample) values
  ('home', 'hero', null, ${q(JSON.stringify({ titleLead: homeContent.heroTitleLead, titleAccent: homeContent.heroTitleAccent, titleTail: homeContent.heroTitleTail, lede: homeContent.heroLede }))}::jsonb, true),
  ('home', 'intro', ${q(homeContent.introTitle)}, ${q(JSON.stringify({ paragraphs: homeContent.intro }))}::jsonb, true);

-- Testimonials (placeholders that explain what goes here)
insert into public.testimonials (quote, author, sort_order, published, is_sample) values
${testimonials.map((t, i) => `  (${q(t.quote)}, ${q(t.author)}, ${i + 1}, true, true)`).join(',\n')};

commit;
`;
writeFileSync(new URL('../supabase/seed/demo.sql', import.meta.url), sql);

const menuSql = `-- SAVORA MENU — owner-supplied (food and drinks menu boards). Prices in kobo (NGN x 100).
-- Generated by scripts/generate-demo-seed.mjs from src/data/menu.js. Do not edit by hand:
-- after launch, change the menu in the admin dashboard instead of re-running this file.
-- Safe to run once on a fresh database (production included).

begin;

insert into public.menu_categories (slug, name, menu_group, sort_order) values
${menuCategories.map((c, i) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.group)}, ${i + 1})`).join(',\n')};

insert into public.menu_items (category_id, name, description, price_kobo, available, featured, tags, sort_order)
select c.id, v.name, v.description, v.price_kobo, true, v.featured, v.tags, v.sort_order
from (values
${menuItems.map((m, i) => `  (${q(m.category)}, ${q(m.name)}, ${q(m.description)}, ${m.price * 100}, ${m.featured}, ${arr(m.tags)}, ${i + 1})`).join(',\n')}
) as v(category, name, description, price_kobo, featured, tags, sort_order)
join public.menu_categories c on c.slug = v.category;

commit;
`;
writeFileSync(new URL('../supabase/seed/menu.sql', import.meta.url), menuSql);
console.log(`wrote supabase/seed/demo.sql and supabase/seed/menu.sql (${menuItems.length} items)`);
